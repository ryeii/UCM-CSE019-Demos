"""Build the offline demo data from the archived, versioned NCBI GenBank records."""
from pathlib import Path
import re, json, hashlib
ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'demos' / 'data'
def read(name):
    raw = (DATA / name).read_text()
    seq = re.sub('[^acgtACGT]', '', raw.split('ORIGIN')[1].split('//')[0]).upper()
    features = re.split(r'\n(?=     \S)', raw.split('FEATURES')[1].split('ORIGIN')[0])
    return raw, seq, features
def feature(features, kind):
    return next(f for f in features if re.match(r'\s+' + kind + r'\s', f) and '/gene="HBB"' in f)
def intervals(f):
    return [[int(a)-1, int(b)] for a,b in re.findall(r'(\d+)\.\.(\d+)',f.split('/')[0])]
def rc(s): return s.translate(str.maketrans('ACGT','TGCA'))[::-1]
graw, genome, gf = read('hbb-region.gb')
traw, transcript, tf = read('hbb-transcript.gb')
assert 'NC_000011.10' in graw and 'NM_000518.5' in traw
assert len(genome)==30000 and len(transcript)==628
span = intervals(feature(gf,'gene'))[0]
exons = intervals(feature(gf,'mRNA'))
cds_parts = intervals(feature(gf,'CDS'))
cds_slice = intervals(feature(tf,'CDS'))[0]
spliced = rc(''.join(genome[a:b] for a,b in exons))
cds = transcript[slice(*cds_slice)]
assert spliced == transcript
assert rc(''.join(genome[a:b] for a,b in cds_parts)) == cds
assert len(cds)==444 and cds[:3]=='ATG' and cds[-3:]=='TAA'
assert cds[18:21]=='GAG' and cds[19]=='A'
# Standard genetic code, in NCBI's TCAG ordering.
amino='FFLLSSSSYY**CC*WLLLLPPPPHHQQRRRRIIIMTTTTNNKKSSRRVVVVAAAADDEEGGGG'
codons=[a+b+c for a in 'TCAG' for b in 'TCAG' for c in 'TCAG']
table=dict(zip(codons,amino))
protein=''.join(table[cds[i:i+3]] for i in range(0,len(cds),3))
annotated=re.search(r'/translation="([^"]+)"',feature(tf,'CDS')).group(1)
assert protein[:-1]==re.sub(r'\s','',annotated) and protein[-1]=='*'
marker=cds[:30]
needle=rc(marker)
hits=[i for i in range(len(genome)-len(needle)+1) if genome[i:i+len(needle)]==needle]
assert hits==[16991], hits
assert span==[15463,17071]
gene=rc(genome[slice(*span)])
# Exons in transcription order, expressed as slices of the oriented gene.
oriented_exons=[[span[1]-b,span[1]-a] for a,b in reversed(exons)]
assert ''.join(gene[a:b] for a,b in oriented_exons)==transcript
payload=dict(accession='NC_000011.10',assembly='GRCh38',regionStart=5210001,regionEnd=5240000,
             transcriptAccession='NM_000518.5',proteinAccession='NP_000509.1',geneId=3043,
             retrieved='2026-10-12',sequence=genome,transcript=transcript,span=span,
             exons=exons,orientedExons=oriented_exons,cdsParts=cds_parts,cdsSlice=cds_slice,
             marker=marker,needle=needle,expectedHits=hits,protein=protein[:-1],
             sha256={name:hashlib.sha256((DATA/name).read_bytes()).hexdigest() for name in ['hbb-region.gb','hbb-transcript.gb']})
(DATA/'hbb-data.js').write_text('/* Generated by scripts/build-hbb-data.py; reference data from NCBI. */\nconst HBB_DATA = '+json.dumps(payload,indent=2)+';\nif (typeof module !== "undefined") module.exports = HBB_DATA;\n')
(DATA/'hbb-region.fasta').write_text('>NC_000011.10:5210001-5240000 Homo sapiens chromosome 11, GRCh38, plus strand\n'+'\n'.join(genome[i:i+80] for i in range(0,len(genome),80))+'\n')
print('Verified 30,000 bp, unique 30-base marker, reverse-strand exons, 628-nt transcript, 444-nt CDS, 147-aa protein, and HbS reference codon.')
print('Gene slices:',oriented_exons,'CDS:',cds_slice,'Marker:',marker)
